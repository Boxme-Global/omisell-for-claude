#!/usr/bin/env python3
"""Maintain the Omisell skills: sync the shared house rules, check, package.

    python3 scripts/skills.py sync      # copy shared/house-rules.md into every SKILL.md
    python3 scripts/skills.py check     # fail on drift or invalid frontmatter (CI)
    python3 scripts/skills.py package   # dist/<skill>.zip for claude.ai upload

Why the rules are copied, not referenced: a skill uploaded to claude.ai is a
standalone zip and cannot read a file outside its own folder, so every
SKILL.md must carry the full text. This script keeps the copies identical.

Stdlib only.
"""

from __future__ import annotations

import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "omisell"
SKILLS = PLUGIN / "skills"
RULES = PLUGIN / "shared" / "house-rules.md"
DIST = ROOT / "dist"

START = "<!-- omisell:house-rules:start (generated by scripts/skills.py sync; edit shared/house-rules.md) -->"
END = "<!-- omisell:house-rules:end -->"
BLOCK_RX = re.compile(
    re.escape("<!-- omisell:house-rules:start") + r".*?" + re.escape(END), re.S
)

# Keys claude.ai / the Skills API accept. Anything else is a hard upload error
# there, even though Claude Code ignores unknown keys.
ALLOWED_KEYS = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
NAME_RX = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MAX_NAME = 64
MAX_DESCRIPTION = 1024


def skill_files() -> list[Path]:
    return sorted(SKILLS.glob("*/SKILL.md"))


def block() -> str:
    return f"{START}\n{RULES.read_text(encoding='utf-8').strip()}\n{END}"


def frontmatter(text: str) -> dict[str, str] | None:
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---\n", 4)
    if end < 0:
        return None
    keys: dict[str, str] = {}
    for line in text[4:end].splitlines():
        if not line or line[0].isspace() or line.startswith("#"):
            continue
        key, _, value = line.partition(":")
        keys[key.strip()] = value.strip().strip('"').strip("'")
    return keys


def sync() -> int:
    rules = block()
    changed = 0
    for path in skill_files():
        text = path.read_text(encoding="utf-8")
        if BLOCK_RX.search(text):
            new = BLOCK_RX.sub(lambda _m: rules, text)
        else:
            new = text.rstrip() + "\n\n" + rules + "\n"
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed += 1
            print(f"synced {path.relative_to(ROOT)}")
    print(f"{changed} file(s) updated, {len(skill_files())} skill(s)")
    return 0


def check() -> int:
    rules = block()
    errors: list[str] = []
    for path in skill_files():
        rel = path.relative_to(ROOT)
        text = path.read_text(encoding="utf-8")
        meta = frontmatter(text)
        if meta is None:
            errors.append(f"{rel}: missing --- frontmatter ---")
            continue
        extra = set(meta) - ALLOWED_KEYS
        if extra:
            errors.append(f"{rel}: keys not accepted by claude.ai: {sorted(extra)}")
        name = meta.get("name", "")
        if name != path.parent.name:
            errors.append(f"{rel}: name '{name}' must equal folder '{path.parent.name}'")
        if not NAME_RX.match(name) or len(name) > MAX_NAME:
            errors.append(f"{rel}: name must be kebab-case, <= {MAX_NAME} chars")
        desc = meta.get("description", "")
        if not desc:
            errors.append(f"{rel}: description is required (one line)")
        elif len(desc) > MAX_DESCRIPTION:
            errors.append(f"{rel}: description is {len(desc)} chars, max {MAX_DESCRIPTION}")
        found = BLOCK_RX.search(text)
        if not found:
            errors.append(f"{rel}: house rules block missing (run: scripts/skills.py sync)")
        elif found.group(0) != rules:
            errors.append(f"{rel}: house rules block is stale (run: scripts/skills.py sync)")
    for err in errors:
        print(f"ERROR {err}")
    print(f"{len(skill_files())} skill(s) checked, {len(errors)} error(s)")
    return 1 if errors else 0


def package() -> int:
    if check():
        return 1
    DIST.mkdir(exist_ok=True)
    for path in skill_files():
        folder = path.parent
        out = DIST / f"omisell-{folder.name}.zip"
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
            for file in sorted(folder.rglob("*")):
                if file.is_file():
                    # Top-level entry must be the skill folder itself.
                    zf.write(file, Path(folder.name) / file.relative_to(folder))
        print(f"packaged {out.relative_to(ROOT)}")
    return 0


def main(argv: list[str]) -> int:
    commands = {"sync": sync, "check": check, "package": package}
    if len(argv) != 2 or argv[1] not in commands:
        print(__doc__)
        return 2
    return commands[argv[1]]()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
